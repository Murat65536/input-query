#[cfg(target_os = "macos")]
use macos::InputHandlerBackend;



/// Cross-platform input handler for querying keyboard key states.
pub struct InputHandler {
    backend: InputHandlerBackend,
}

impl InputHandler {
    /// Creates a new input handler.
    pub fn new() -> Self {
        Self {
            backend: InputHandlerBackend::new(),
        }
    }

    /// Checks if a specific key is currently pressed.
    ///
    /// # Arguments
    ///
    /// * `key` - The key code to check
    ///
    /// # Returns
    ///
    /// `true` if the key is currently pressed, `false` otherwise.
    pub fn is_pressed(&self, key: KeyCode) -> bool {
        self.backend.is_pressed(key)
    }
}


